function convertKindToReadable(kind, dict) {
    if (!kind) return '';
    var kinds = (kind.indexOf(',') !== -1) ? kind.split(',').map(function (s) { return s.trim(); }) : [kind];
    var table = KIND_TABLES[dict] || KIND_TABLES['jaen'] || {};
    return kinds.map(function (k) { return (k in table) ? table[k] : k; }).join(', ');
}
