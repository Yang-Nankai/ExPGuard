  function router(request, sender, sendResponse) {
    let error;
    switch (request.uri) {
      case "cookies":
        import_webextension_polyfill.default.cookies[request.method](request.args[0]).catch((err) => error = err).then((data) => {
          sendResponse({
            status: error ? 500 : 200,
            error,
            data
          });
        });
        return true;
      case "check_version":
        sendResponse({
          status: 200,
          data: { version }
        });
        return true;
      case "socket":
        doWebSocket(request.args[0], request.args[1]).then(sendResponse);
        return true;
      default:
        sendResponse({
          status: 404,
          error: { message: "Unknown request to Chrome Extension" }
        });
        return false;
    }
  }

